from __future__ import annotations

import os
from typing import Optional, Protocol

try:
    import qaic
except ImportError:  # QAIC SDK is only available in Cloud AI runtime containers.
    qaic = None

from qaic_models.base.predict_base import CPUPredictor, QAICPredictor

from .postprocess import CHARS, postprocess_lprnet
from .preprocess import INPUT_NAME, preprocess_plate_image
from .visualize import visualize_plate

SUPPORTED_VARIANTS = ("lprnet",)
DEFAULT_VARIANT = "lprnet"
FINAL_ONNX_NAME = "lprnet_fp16ready.onnx"
LATENCY_QPC_SUBDIR = "qpc_latency"
THROUGHPUT_QPC_SUBDIR = "qpc_throughput"


class _LPRNetPredictor(Protocol):
    def predict(self, image_path: str, output_path: Optional[str]) -> dict: ...


class _LPRNetRecipeMixin:
    """OCR-task preprocess/postprocess/visualize shared by CPU and QAIC backends."""

    LABELS_URL = ""
    LABELS_TMP = ""

    def preprocess(self, image_path: str) -> dict:
        return {INPUT_NAME: preprocess_plate_image(image_path)}

    def postprocess(self, outputs, latency_ms: float) -> dict:
        prediction = postprocess_lprnet(outputs, self._get_labels() or CHARS)
        return {"prediction": prediction, "latency_ms": latency_ms}

    def visualize(self, image_path: str, prediction, output_path: str):
        visualize_plate(image_path, prediction, output_path, self.get_font)


def _require_variant(variant: str) -> str:
    if variant not in SUPPORTED_VARIANTS:
        raise ValueError(
            f"Unsupported LPRNet variant: {variant!r}. Supported variants: {', '.join(SUPPORTED_VARIANTS)}."
        )
    return variant


class LPRNetOnnxCPU(_LPRNetRecipeMixin, CPUPredictor):
    """CPU reference runner for LPRNet, backed by ONNX Runtime CPU.

    `model_path` may be either a generated ONNX file directly, or a work
    directory produced by `export.py` — in which case the default
    "lprnet_fp16ready.onnx" artifact name is resolved inside it. The package
    never bundles or reads a committed ONNX file; the artifact must already
    have been generated by export.py into a caller-supplied directory.
    """

    def __init__(self, model_path: str, variant: str = DEFAULT_VARIANT, providers: Optional[list[str]] = None):
        variant = _require_variant(variant)
        resolved_path = self._resolve_onnx_path(model_path, variant)
        super().__init__(resolved_path, providers=providers)

    @staticmethod
    def _resolve_onnx_path(model_path: str, variant: str) -> str:
        if model_path.endswith(".onnx"):
            return os.path.abspath(model_path)
        candidate = os.path.join(model_path, FINAL_ONNX_NAME)
        if os.path.exists(candidate):
            return os.path.abspath(candidate)
        raise FileNotFoundError(
            f"No generated ONNX artifact found at {candidate!r}. "
            "Run `python -m qaic_models.vision.ocr.lprnet.export` first."
        )


class LPRNetQaic(_LPRNetRecipeMixin, QAICPredictor):
    """QAIC/QPC runtime for LPRNet via qaic.Session.

    `qpc_dir` may be either a QPC directory containing `programqpc.bin`
    directly, or a work directory produced by `export.py` — in which case the
    latency-tuned "qpc_latency" subdirectory is resolved inside
    it. The package never bundles or reads a committed QPC binary; it must
    already have been compiled by export.py into a caller-supplied directory.
    """

    def __init__(self, qpc_dir: str, providers: Optional[list[str]] = None, device_id: int | None = None):
        if qaic is None:
            raise ImportError("qaic module not available; install the QAIC SDK to use LPRNetQaic.")
        resolved_dir = self._resolve_qpc_dir(qpc_dir)
        super().__init__(resolved_dir, device_id=device_id)
        self.providers = providers or ["QAicExecutionProvider"]

    @classmethod
    def _resolve_qpc_dir(cls, qpc_dir: str) -> str:
        # QAICPredictor._resolve_qpc() anchors relative paths to the directory of
        # the module defining this subclass (model.py), which is meaningless for
        # a caller-supplied generated-artifact directory. Return an absolute path
        # so QAICPredictor uses it as-is.
        if os.path.exists(os.path.join(qpc_dir, "programqpc.bin")):
            return os.path.abspath(qpc_dir)
        candidate = os.path.join(qpc_dir, LATENCY_QPC_SUBDIR)
        if os.path.exists(os.path.join(candidate, "programqpc.bin")):
            return os.path.abspath(candidate)
        raise FileNotFoundError(
            f"No generated QPC found at {qpc_dir!r} or {candidate!r}. "
            "Run `python -m qaic_models.vision.ocr.lprnet.export` first."
        )


class LPRNet:
    """Factory wrapper selecting the CPU reference or QAIC backend by provider.

    Example:
        m = LPRNet(work_dir, provider="CPUExecutionProvider")
        m = LPRNet(work_dir, provider="QAicExecutionProvider")
    """

    @classmethod
    def from_compiled(cls, artifact_dir: str, variant: str = DEFAULT_VARIANT, provider: str = "QAicExecutionProvider", device_id: int | None = None, **kwargs):
        if kwargs:
            unexpected = ", ".join(sorted(kwargs))
            raise TypeError(f"Unexpected keyword argument(s): {unexpected}")
        return cls(artifact_dir, variant=variant, provider=provider, device_id=device_id)

    def __init__(self, artifact_dir: str, variant: str = DEFAULT_VARIANT, provider: str = "QAicExecutionProvider", device_id: int | None = None):
        provider = provider.strip()
        if provider == "CPUExecutionProvider":
            self._impl: _LPRNetPredictor = LPRNetOnnxCPU(artifact_dir, variant=variant, providers=[provider])
        elif provider == "QAicExecutionProvider":
            self._impl = LPRNetQaic(artifact_dir, providers=[provider], device_id=device_id)
        else:
            raise ValueError(f"Unsupported provider: {provider}")

    def predict(self, image_path: str, output_path: Optional[str] = None) -> dict:
        return self._impl.predict(image_path, output_path)
