#
# roofline.py - Compute a 3-ceiling roofline (HMX / HVX / DDR) for a compiled+profiled
# Cloud AI 100 vision QPC, from artifacts Step 2 (compile) and Step 3a (qaic_profile.sh)
# of this skill already produce. No extra compile or profiling run is performed here.
#
# Usage:
#   python3 roofline.py --compile-log compile.log \
#       --summary qaic_stats_out/<sample>.qaic-opstats.summary.txt \
#       --runner-log qaic_stats_out/qaic_runner_stats.log \
#       --sku ultra --precision fp16 --cores 16 --instances 1 \
#       [--measured-inf-s 2341] [--graph-name QAicGraph]
#
# Inputs:
#   --compile-log   compile.log from a `-aic-perf-metrics` compile (Step 2). Provides
#                   "Original MAC estimate", "AIC HMX/non-HMX MAC estimate", and per-core
#                   compile-estimated "DDR traffic read" (steady-state default DDR source).
#   --summary       raw *.qaic-opstats.summary.txt generated by qaic-opstats from Step 3a.
#                   Provides full per-core, per-op ucycles. Do not pass only the printed
#                   top-20 excerpt if full aggregation is required.
#   --runner-log    qaic-runner stdout captured by qaic_profile.sh as qaic_runner_stats.log.
#                   Provides graph-suffixed EffectiveFrequencyMHz and InfPCycles metrics, plus
#                   optional graph-suffixed DDR metrics. This is required; raw opstats summaries
#                   do not contain frequency. Use --graph-name when the log has multiple graphs.
#
# Method:
#   HMX nameplate roofline:      t = 2*MAC / datasheet_peak_ops_per_second
#   HMX observed-clock roofline: t = 2*MAC / (MAC_per_clock_per_core * cores * observed_clock)
#   HVX active lower bound:      t = sum(HVX-resource ucycles) / observed_clock
#   DDR roofline:                t = steady-state DDR bytes/inf / SKU_DDR_BW
#
# Note: HVX is reported as an active-cycle lower bound until correlated against InfPCycles and
# measured wall latency across more models. The ceiling and attribution use measured ucycles;
# the HVX class table is for readable attribution only.

from __future__ import annotations

import argparse
import math
import re
import sys
from collections import defaultdict
from pathlib import Path

# ── Hardware constants ──────────────────────────────────────────────────────────────
# SKU table: card-level TOPS/TFLOPS (cloud_ai_soc_architecture.md §1), normalized here
# to a single SoC. Ultra = 4 SoCs/card, Pro = 1 SoC/card.
SKUS = {
    "standard": {"cores": 14, "fp16_tflops": 110.0, "int8_tops": 325.0, "ddr_bw_gbs": 137.0},
    "pro":      {"cores": 16, "fp16_tflops": 125.0, "int8_tops": 375.0, "ddr_bw_gbs": 137.0},
    "ultra":    {"cores": 16, "fp16_tflops": 290.0 / 4, "int8_tops": 870.0 / 4, "ddr_bw_gbs": 548.0 / 4},
}

# Observed-clock HMX model: derive per-core MAC/clock from Pro nameplate. This reconciles
# Ultra measurements better when EffectiveFrequencyMHz is the observed runtime clock.
# 1 MAC = 2 ops; Pro Fmax is 1450 MHz; Pro nameplate is 125 TFLOP/s and 375 TOP/s.
PRO_FMAX_MHZ = 1450.0
FP16_MAC_PER_CLOCK_PER_CORE = 125.0e12 / (2.0 * 16.0 * PRO_FMAX_MHZ * 1.0e6)
INT8_OPS_PER_CLOCK_PER_CORE = 375.0e12 / (16.0 * PRO_FMAX_MHZ * 1.0e6)

# ── HVX op-class table (attribution only; measured ucycles are authoritative) ──────
HVX_OP_CLASSES = [
    ("softmax",          "reduction+transcendental"),
    ("layernorm",        "reduction+transcendental"),
    ("normalization",    "reduction+transcendental"),
    ("erf",              "elementwise-transcendental"),
    ("sigmoid",          "elementwise-transcendental"),
    ("elementadd",       "elementwise-simple"),
    ("elementmul",       "elementwise-simple"),
    ("elementsub",       "elementwise-simple"),
    ("broadcastadd",     "elementwise-simple"),
    ("broadcastmul",     "elementwise-simple"),
    ("mulsplat",         "elementwise-simple"),
    ("maxsplat",         "elementwise-simple"),
    ("transpose",        "data-movement"),
    ("copysamevtcm",     "data-movement"),
    ("copytovtcm",       "data-movement"),
    ("copyfromvtcm",     "data-movement"),
    ("multicastvtcm",    "data-movement"),
    ("extracttensor",    "data-movement"),
    ("inserttensor",     "data-movement"),
    ("converttod32",     "format-conversion"),
    ("convertfromd32",   "format-conversion"),
    ("convertweightstod32", "format-conversion"),
    ("decimated32",      "format-conversion"),
    ("maxpoold32",       "pooling-resize"),
    ("avgpoold32",       "pooling-resize"),
    ("upsample",         "pooling-resize"),
    ("spacetodepth",     "format-conversion"),
    ("padzerod32",       "pooling-resize"),
    ("sync",             "sync-barrier"),
    ("barrier",          "sync-barrier"),
    ("semaphore",        "sync-barrier"),
    ("endcyclestats",    "sync-barrier"),
    ("splat",            "elementwise-simple"),
]


def classify_hvx_op(op_name: str) -> str:
    name = op_name.lower()
    for pattern, cls in HVX_OP_CLASSES:
        if pattern in name:
            return cls
    return "other"


# ── compile.log parsing ─────────────────────────────────────────────────────────────

_MAC_RE = re.compile(r"^(Original|AIC HMX|AIC non-HMX) MAC estimate:\s*([\d,]+)", re.MULTILINE)
_VTCM_RE = re.compile(r"^VTCMMaxSize:\s*([\d.]+)\s*MB", re.MULTILINE)
_DDR_CORE_READ_RE = re.compile(
    r"^\s*c\d+: DDR traffic\s+read:\s*([\d,]+)\s*KB\s*\(first-inf\s*([\d,]+)\s*KB\)",
    re.MULTILINE,
)


def parse_compile_log(text: str) -> dict:
    macs = {}
    for m in _MAC_RE.finditer(text):
        macs[m.group(1)] = int(m.group(2).replace(",", ""))

    vtcm_match = _VTCM_RE.search(text)
    vtcm_mb = float(vtcm_match.group(1)) if vtcm_match else None

    steady_kb = 0
    first_inf_kb = 0
    core_count = 0
    for m in _DDR_CORE_READ_RE.finditer(text):
        steady_kb += int(m.group(1).replace(",", ""))
        first_inf_kb += int(m.group(2).replace(",", ""))
        core_count += 1

    return {
        "original_mac": macs.get("Original"),
        "hmx_mac": macs.get("AIC HMX"),
        "non_hmx_mac": macs.get("AIC non-HMX"),
        "vtcm_max_mb": vtcm_mb,
        "ddr_steady_kb": steady_kb,
        "ddr_first_inf_kb": first_inf_kb,
        "ddr_core_count": core_count,
    }


# ── runner log parsing ──────────────────────────────────────────────────────────────

_RUNNER_METRIC_RE = re.compile(
    r"^(?P<name>EffectiveFrequencyMHz|InfPCycles|DDRTrafficMB|DDRBandwidthGBPerSec)_"
    r"(?P<graph>[^,]+),\s*(?P<value>[\d.]+)",
    re.MULTILINE,
)
_RUNNER_THROUGHPUT_RE = re.compile(r"InferenceCnt\s+(\d+)\s+TotalDuration\s+(\d+)us\s+BatchSize\s+(\d+)\s+Inf/Sec\s+([\d.]+)")


def parse_runner_log(text: str, graph_name: str | None = None) -> dict:
    metrics_by_graph: dict[str, dict[str, float]] = defaultdict(dict)
    for match in _RUNNER_METRIC_RE.finditer(text):
        metrics_by_graph[match.group("graph")][match.group("name")] = float(match.group("value"))

    if not metrics_by_graph:
        raise ValueError("no graph-suffixed runner metrics found")
    if graph_name is None:
        if len(metrics_by_graph) != 1:
            suffixes = ", ".join(sorted(metrics_by_graph))
            raise ValueError(f"multiple runner graph suffixes ({suffixes}); pass --graph-name")
        graph_name = next(iter(metrics_by_graph))
    if graph_name not in metrics_by_graph:
        suffixes = ", ".join(sorted(metrics_by_graph))
        raise ValueError(f"runner graph suffix '{graph_name}' not found; available: {suffixes}")

    metrics = metrics_by_graph[graph_name]
    for metric in ("EffectiveFrequencyMHz", "InfPCycles"):
        if metric not in metrics:
            raise ValueError(f"runner graph suffix '{graph_name}' lacks {metric}")

    tput_match = _RUNNER_THROUGHPUT_RE.search(text)
    runner_summary = None
    if tput_match:
        runner_summary = {
            "inference_count": int(tput_match.group(1)),
            "total_duration_us": int(tput_match.group(2)),
            "batch_size": int(tput_match.group(3)),
            "inf_s": float(tput_match.group(4)),
        }
    return {
        "graph_name": graph_name,
        "effective_freq_mhz": metrics["EffectiveFrequencyMHz"],
        "inf_pcycles": metrics["InfPCycles"],
        "ddr_traffic_mb": metrics.get("DDRTrafficMB"),
        "ddr_bandwidth_gbs": metrics.get("DDRBandwidthGBPerSec"),
        "runner_summary": runner_summary,
        "metrics": metrics,
        "metrics_by_graph": dict(metrics_by_graph),
    }


# ── opstats summary parsing ─────────────────────────────────────────────────────────

# Raw summary rows:
# c0    1481460      72.02%         N/A ... N/A  sync HMX
# Printed qaic_profile top-op rows are also accepted for backward-compatible testing:
#   526900  25.62%  aicsoftmaxd32 HVX TCM (float16, i8)
_PRINTED_OP_ROW_RE = re.compile(
    r"^\s*(\d+)\s+[\d.]+%\s+(\S+)\s+(HVX|HMX|DMAIssue)\b.*$", re.MULTILINE
)
_THREAD_UTIL_RE = re.compile(
    r"(HVX|HMX|DMAIssue)[^\d\n]*avg\s*([\d.]+)%", re.MULTILINE
)
_RESOURCE_RE = re.compile(r"\b(HVX|HMX|DMAIssue)\b")


def _parse_opdetails(opdetails: str) -> tuple[str, str] | None:
    resource_match = _RESOURCE_RE.search(opdetails)
    if not resource_match:
        return None
    resource = resource_match.group(1)
    before_resource = opdetails[:resource_match.start()].strip()
    if not before_resource:
        return None
    # Raw opdetails may start with an op kind followed by a graph op path. Keep kind as the op name.
    op_name = before_resource.split()[0]
    return op_name, resource


def _parse_raw_summary_line(line: str) -> tuple[int, str, str, int] | None:
    """Parse one raw qaic-opstats summary row.

    Column layout is:
      core ucycles ucycles(%) pcycles pcycles(%) count out_KB ucycles/KB pcycles/KB stddev opdetails
    The header says "out KB" as two words, but the row value is one token. Use maxsplit=10 so
    opdetails stays intact even when it contains graph paths and parenthesized dtype text.
    """
    if not re.match(r"^c\d+\s+", line):
        return None
    parts = line.split(None, 10)
    if len(parts) < 11:
        return None
    core_token, ucycles_token, opdetails = parts[0], parts[1], parts[10]
    if core_token.endswith("total:") or not core_token[1:].isdigit():
        return None
    try:
        core = int(core_token[1:])
        ucycles = int(ucycles_token)
    except ValueError:
        return None
    parsed = _parse_opdetails(opdetails)
    if parsed is None:
        return None
    name, resource = parsed
    return core, name, resource, ucycles


def parse_opstats_summary(text: str) -> dict:
    ops = []  # list of (core, name, resource, ucycles)
    for line in text.splitlines():
        parsed_row = _parse_raw_summary_line(line)
        if parsed_row is not None:
            ops.append(parsed_row)

    # Backward compatibility for old combined logs that only have the printed top-20 rows.
    if not ops:
        for m in _PRINTED_OP_ROW_RE.finditer(text):
            ucycles, name, resource = int(m.group(1)), m.group(2), m.group(3)
            ops.append((0, name, resource, ucycles))

    thread_util = {}
    for m in _THREAD_UTIL_RE.finditer(text):
        thread_util[m.group(1)] = float(m.group(2))

    return {
        "ops": ops,
        "thread_util_pct": thread_util,
    }


# ── roofline computation ────────────────────────────────────────────────────────────

def seconds_to_img_s(seconds: float) -> float:
    if seconds == 0:
        return float("inf")
    if not math.isfinite(seconds):
        return float("nan")
    return 1.0 / seconds


def compute_roofline(compile_data: dict, summary_data: dict, runner_data: dict,
                     sku: str, precision: str,
                     cores: int, instances: int) -> dict:
    sku_spec = SKUS[sku]
    cores_in_use = min(cores * instances, sku_spec["cores"])

    original_mac = compile_data["original_mac"] or 0
    hmx_mac = compile_data["hmx_mac"] or 0
    flops = 2 * original_mac

    if precision == "int8":
        nameplate_peak_ops_per_soc = sku_spec["int8_tops"] * 1e12
        observed_peak_ops = INT8_OPS_PER_CLOCK_PER_CORE * cores_in_use * (runner_data["effective_freq_mhz"] or 0) * 1e6
    else:
        nameplate_peak_ops_per_soc = sku_spec["fp16_tflops"] * 1e12
        observed_peak_ops = 2.0 * FP16_MAC_PER_CLOCK_PER_CORE * cores_in_use * (runner_data["effective_freq_mhz"] or 0) * 1e6

    nameplate_peak = nameplate_peak_ops_per_soc * (cores_in_use / sku_spec["cores"])
    t_hmx_nameplate_s = flops / nameplate_peak if nameplate_peak > 0 else float("inf")
    t_hmx_observed_s = flops / observed_peak_ops if observed_peak_ops > 0 else float("inf")

    # HVX active-cycle lower bound: aggregate by core, take max core time as a wall-time lower bound.
    hvx_by_core = defaultdict(int)
    hmx_by_core = defaultdict(int)
    dma_by_core = defaultdict(int)
    by_class = defaultdict(int)
    unclassified_ops = set()
    for core, name, resource, ucycles in summary_data["ops"]:
        if resource == "HVX":
            hvx_by_core[core] += ucycles
            cls = classify_hvx_op(name)
            by_class[cls] += ucycles
            if cls == "other":
                unclassified_ops.add(name)
        elif resource == "HMX":
            hmx_by_core[core] += ucycles
        elif resource == "DMAIssue":
            dma_by_core[core] += ucycles

    freq_mhz = runner_data["effective_freq_mhz"]
    if freq_mhz and freq_mhz > 0:
        t_hvx_active_s = (max(hvx_by_core.values()) if hvx_by_core else 0) / (freq_mhz * 1e6)
        t_hmx_active_s = (max(hmx_by_core.values()) if hmx_by_core else 0) / (freq_mhz * 1e6)
        t_dma_active_s = (max(dma_by_core.values()) if dma_by_core else 0) / (freq_mhz * 1e6)
    else:
        t_hvx_active_s = t_hmx_active_s = t_dma_active_s = float("inf")

    if runner_data["ddr_traffic_mb"] is not None:
        ddr_bytes = runner_data["ddr_traffic_mb"] * 1024 * 1024
        ddr_source = f"measured (qaic-runner {runner_data['graph_name']})"
    else:
        ddr_bytes = compile_data["ddr_steady_kb"] * 1024
        ddr_source = "estimate (compile.log)"
    ddr_bw_bytes_s = sku_spec["ddr_bw_gbs"] * 1e9
    t_ddr_s = ddr_bytes / ddr_bw_bytes_s if ddr_bw_bytes_s > 0 else float("inf")

    ceilings = {
        "HMX_nameplate": t_hmx_nameplate_s,
        "HMX_observed_clock": t_hmx_observed_s,
        "DDR": t_ddr_s,
    }
    # HVX active time is a measured lower bound, not a validated theoretical roofline; keep it out of argmax.
    bound = max(ceilings, key=ceilings.get)
    best_time_s = ceilings[bound]

    hmx_pad_ratio = ((hmx_mac - original_mac) / original_mac) if original_mac else None

    return {
        "cores_in_use": cores_in_use,
        "flops_per_inf": flops,
        "ceilings_s": ceilings,
        "ceilings_img_s": {k: seconds_to_img_s(v) for k, v in ceilings.items()},
        "bound": bound,
        "best_ceiling_img_s": seconds_to_img_s(best_time_s),
        "hmx_pad_ratio": hmx_pad_ratio,
        "ddr_source": ddr_source,
        "hvx_active_lower_bound_s": t_hvx_active_s,
        "hmx_active_lower_bound_s": t_hmx_active_s,
        "dma_active_lower_bound_s": t_dma_active_s,
        "hvx_attribution_ucycles": dict(by_class),
        "hvx_ucycles_total": sum(hvx_by_core.values()),
        "unclassified_hvx_ops": sorted(unclassified_ops),
    }


# ── CLI / report ─────────────────────────────────────────────────────────────────────

def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--compile-log", required=True, type=Path,
                    help="compile.log from a -aic-perf-metrics compile (Step 2)")
    p.add_argument("--summary", required=True, type=Path,
                    help="raw *.qaic-opstats.summary.txt generated by qaic-opstats")
    p.add_argument("--runner-log", required=True, type=Path,
                    help="qaic-runner stdout captured by qaic_profile.sh as qaic_runner_stats.log")
    p.add_argument("--graph-name", default=None,
                    help="runner metric graph suffix; required when the log contains multiple graphs")
    p.add_argument("--sku", required=True, choices=sorted(SKUS.keys()))
    p.add_argument("--precision", required=True, choices=["fp16", "int8"])
    p.add_argument("--cores", required=True, type=int)
    p.add_argument("--instances", type=int, default=1)
    p.add_argument("--measured-inf-s", type=float, default=None,
                    help="measured throughput (img/s) from the configurator row or stability run")
    return p


def require_path(path: Path, label: str) -> None:
    if not path.exists():
        print(f"File not found ({label}): {path}", file=sys.stderr)
        sys.exit(1)


def main() -> None:
    parser = build_parser()
    args = parser.parse_args()

    require_path(args.compile_log, "compile log")
    require_path(args.summary, "opstats summary")
    require_path(args.runner_log, "runner log")

    compile_data = parse_compile_log(args.compile_log.read_text())
    if compile_data["original_mac"] is None:
        print(f"No 'Original MAC estimate' found in {args.compile_log} - "
              f"was it compiled with -aic-perf-metrics?", file=sys.stderr)
        sys.exit(1)

    summary_data = parse_opstats_summary(args.summary.read_text())
    if not summary_data["ops"]:
        print(f"No per-op ucycles rows found in {args.summary} - "
              f"expected raw *.qaic-opstats.summary.txt", file=sys.stderr)
        sys.exit(1)

    try:
        runner_data = parse_runner_log(args.runner_log.read_text(), args.graph_name)
    except ValueError as error:
        parser.error(str(error))

    result = compute_roofline(
        compile_data, summary_data, runner_data,
        sku=args.sku, precision=args.precision, cores=args.cores, instances=args.instances,
    )

    print(f"SKU: {args.sku}  precision: {args.precision}  "
          f"cores_in_use: {result['cores_in_use']} (compiled cores={args.cores} x instances={args.instances})")
    print(f"Observed frequency: {runner_data['effective_freq_mhz']:.3f} MHz"
          + (f"  InfPCycles: {runner_data['inf_pcycles']:.0f}" if runner_data["inf_pcycles"] else ""))
    print(f"FLOPs/inf: {result['flops_per_inf']:,}  "
          f"(Original MAC {compile_data['original_mac']:,}"
          + (f", HMX-tiled MAC {compile_data['hmx_mac']:,}, pad ratio {result['hmx_pad_ratio']:.1%}"
             if result["hmx_pad_ratio"] is not None else "") + ")")
    if compile_data["non_hmx_mac"]:
        print(f"WARNING: AIC non-HMX MAC estimate = {compile_data['non_hmx_mac']:,} "
              f"(non-zero - some Conv/MatMul missed HMX)")
    print()

    print("Ceilings:")
    for unit in ("HMX_nameplate", "HMX_observed_clock", "DDR"):
        t_s = result["ceilings_s"][unit]
        img_s = result["ceilings_img_s"][unit]
        marker = "  <-- bound" if unit == result["bound"] else ""
        print(f"  {unit}: {t_s * 1000:.4f} ms/inf  ({img_s:,.1f} img/s){marker}")
    print(f"  DDR ceiling source: {result['ddr_source']}")
    print()

    print("Measured active-cycle lower bounds (not theoretical ceilings):")
    print(f"  HMX active: {result['hmx_active_lower_bound_s'] * 1000:.4f} ms/inf")
    print(f"  HVX active: {result['hvx_active_lower_bound_s'] * 1000:.4f} ms/inf")
    print(f"  DMA active: {result['dma_active_lower_bound_s'] * 1000:.4f} ms/inf")
    print()

    print(f"Roofline bound: {result['bound']}  "
          f"(best ceiling: {result['best_ceiling_img_s']:,.1f} img/s)")

    if args.measured_inf_s is not None:
        pct = args.measured_inf_s / result["best_ceiling_img_s"] * 100.0
        print(f"Measured: {args.measured_inf_s:,.1f} img/s  "
              f"({pct:.1f}% of {result['bound']} roofline)")

    if result["hvx_ucycles_total"] > 0:
        print()
        print("HVX attribution (share of total HVX ucycles):")
        for cls, ucyc in sorted(result["hvx_attribution_ucycles"].items(), key=lambda kv: -kv[1]):
            share = ucyc / result["hvx_ucycles_total"] * 100.0
            print(f"  {cls:28s} {share:5.1f}%")

    if result["unclassified_hvx_ops"]:
        print()
        print(f"WARNING: {len(result['unclassified_hvx_ops'])} HVX op(s) not in the cost table "
              f"(counted toward the HVX active lower bound and toward the 'other' class; "
              f"attribution detail is reduced, the bound itself is unaffected): "
              + ", ".join(result["unclassified_hvx_ops"]))


if __name__ == "__main__":
    main()
